import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const SITUATIONS_DIR = join(PKG_ROOT, "situations");
export const INDEX_FILE = join(PKG_ROOT, "src/bank.generated.ts");
export const REPO_ROOT = resolve(PKG_ROOT, "../..");

export function situationFiles(): string[] {
  return readdirSync(SITUATIONS_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort();
}

export function readSituationFile(file: string): unknown {
  return JSON.parse(readFileSync(join(SITUATIONS_DIR, file), "utf8"));
}

function importName(file: string): string {
  return "s_" + file.replace(/\.json$/, "").replace(/[^a-z0-9]/gi, "_");
}

export function renderIndex(files: string[]): string {
  const lines = [
    "// GENERATED by `pnpm content:index` — do not edit. Validated by `pnpm content:validate`.",
    'import type { Situation } from "./schema.ts";',
    ...files.map((f) => `import ${importName(f)} from "../situations/${f}";`),
    "",
    "export const bank: readonly Situation[] = [",
    ...files.map((f) => `  ${importName(f)},`),
    "] as unknown as readonly Situation[];",
    "",
  ];
  return lines.join("\n");
}
